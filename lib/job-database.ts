export const industries = Array.from(new Set(jobDatabase.map((j) => j.industry)));

export function searchJobs(keyword: string, industry?: string): JobEntry[] {
  const kw = keyword.toLowerCase().trim();
  return jobDatabase.filter((job) => {
    if (industry && job.industry !== industry) return false;
    if (!kw) return true;
    return (
      job.title.toLowerCase().includes(kw) ||
      job.industry.toLowerCase().includes(kw)
    );
  });
}
