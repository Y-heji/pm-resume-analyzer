export const industries = [...new Set(jobDatabase.map(j => j.industry))];

export function searchJobs(keyword: string, industry?: string) {
  const kw = keyword.toLowerCase().trim();
  if (!kw && !industry) return jobDatabase;

  const match = (s: string) => s.toLowerCase().includes(kw);
  return jobDatabase.filter(job => {
    if (industry && job.industry !== industry) return false;
    if (!kw) return true;
    return match(job.title) || match(job.industry) || match(job.jd);
  });
}
